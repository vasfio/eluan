#!/usr/bin/env node
// Writes skills/eluan/DESIGN.md: design tokens as YAML frontmatter plus a short
// rationale. By default it exports the built-in `minimal` theme from
// packages/tokens/src. With --accent it exports a brand theme from
// @eluan/theme-generator instead (colours only; type, spacing and corners
// always come from the token CSS, because the generator doesn't control them).
//
// Usage:
//   node scripts/skills/export-design-md.mjs [--check]
//   node scripts/skills/export-design-md.mjs --accent "#2F6F5E" [--accent …] [--name forest] [--out path]

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import {
  colourNames, context, curveNames, fluidRange, scaleSort, spacingNames, steps, themeNames, value,
} from "./lib/tokens.mjs";

const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const opt = (flag) => args.flatMap((a, i) => (a === flag && args[i + 1] ? [args[i + 1]] : []));
const accents = opt("--accent");
const themeName = opt("--name")[0] ?? (accents.length ? "custom" : "minimal");
const OUT = opt("--out")[0] ?? "skills/eluan/DESIGN.md";

// ---------- Colours ----------

let light;
let dark;
let source;
if (accents.length) {
  // The workspace build, so this works without adding the package to the root
  const gen = new URL("../../packages/theme-generator/dist/index.js", import.meta.url);
  if (!existsSync(gen)) {
    console.error("Build the theme generator first: pnpm --filter @eluan/theme-generator build");
    process.exit(1);
  }
  const { generateTheme, compileCreateThemeTokens } = await import(gen.href);
  const result = generateTheme({ accents, themeName, minContrast: 4.5, neutralTintRatio: 0.04 });
  const strip = (map) => Object.fromEntries(Object.entries(map).map(([k, v]) => [k.replace(/^--/, ""), v]));
  light = strip(result.createThemeTokens);
  dark = strip(compileCreateThemeTokens(result.semanticMap, result.primitives, "dark"));
  source = `@eluan/theme-generator from ${accents.join(", ")} at min contrast 4.5`;
} else {
  const darkCtx = context({ mode: "dark" });
  light = Object.fromEntries(colourNames().map((n) => [n, value(n)]));
  dark = Object.fromEntries(colourNames().map((n) => [n, value(n, darkCtx)]));
  source = "the built-in minimal theme";
}

// ---------- Everything else (always from the token CSS) ----------

const families = Object.fromEntries(
  themeNames.filter((n) => n.startsWith("font-")).map((n) => [n.replace(/^font-/, ""), value(n)]),
);
const typeScale = Object.fromEntries(
  steps.map((s) => {
    const [small, large] = fluidRange(`font-size-step-${s}`);
    return [
      `step-${s}`,
      { size: `${small} to ${large}`, lineHeight: value(`line-height-step-${s}`), letterSpacing: value(`letter-spacing-step-${s}`) },
    ];
  }),
);
const scale = (prefix) =>
  Object.fromEntries(
    spacingNames
      .filter((n) => n.startsWith(prefix))
      .sort((a, b) => scaleSort(a, b, prefix))
      .map((n) => [n.slice(prefix.length), value(n)]),
  );
const rounded = {
  ...Object.fromEntries(curveNames.sort((a, b) => scaleSort(a, b, "curves-")).map((n) => [n.replace(/^curves-/, ""), value(n)])),
  full: value("radius-radius-full"),
};

// ---------- YAML ----------

// Plain scalars only when they start with a letter or digit, aren't numbers, and carry no YAML syntax (# starts a comment)
const q = (v) => (/^[A-Za-z0-9][\w.%() -]*$/.test(String(v)) && !/^-?[\d.]+$/.test(String(v)) ? String(v) : JSON.stringify(String(v)));
function yaml(obj, indent = 0) {
  const pad = " ".repeat(indent);
  return Object.entries(obj)
    .map(([k, v]) =>
      v && typeof v === "object" ? `${pad}${k}:\n${yaml(v, indent + 2)}` : `${pad}${k}: ${q(v)}`,
    )
    .join("\n");
}

const pkg = JSON.parse(readFileSync("packages/tokens/package.json", "utf8"));
const front = {
  name: accents.length ? `Eluan (${themeName})` : "Eluan (minimal)",
  description: "Design tokens for apps built with @eluan/core. Token names are the CSS custom properties without the leading dashes.",
  source: `${source}, with @eluan/tokens ${pkg.version}`,
  defaults: { mode: "light", spacing: "standard", curves: "slight", typeset: "fluid" },
  colors: { light, dark },
  typography: { families, scale: typeScale },
  spacing: scale("spacing-"),
  sizes: scale("size-"),
  rounded,
};

const body = `# ${front.name}

Generated by \`scripts/skills/export-design-md.mjs\`; don't edit by hand. Run \`pnpm skills:build\` to refresh it.

## How to read these tokens

- Every key under \`colors\`, \`spacing\`, \`sizes\` and \`rounded\` is a CSS custom property: \`container-bg\` is \`var(--container-bg)\`. Use the custom property in code, never the resolved value.
- Colours are semantic. Pair a background with the foreground of the same family and state (\`container-bg\` with \`container-fg\`). Contrast between pairs is checked when a theme is generated, so don't change one side of a pair.
- \`spacing\`, \`sizes\` and \`rounded\` show the default density (\`standard\`) and corner style (\`slight\`). \`EluanProvider\`'s \`defaultSpacing\` and \`defaultCurves\` change them app-wide.
- Type sizes are fluid between 480px and 1024px viewports. Always apply a step's size, line height and letter spacing together, or use the \`Typography\` component.
- Eluan has no shadow or motion tokens yet. Use component props (Card \`elevation\`) instead of writing shadows or transitions.

## Rationale

Eluan themes through three layers of custom properties: primitives, modes (light, dim, dark) and the semantic theme layer components read. \`minimal\` is the only built-in theme; brand themes are generated from one to three accent colours with \`@eluan/theme-generator\` and registered with \`createTheme\`. The generator controls colour only. Density, corner style and type scale are Provider settings, so one product can switch them without a new theme.

See \`SKILL.md\` for which component to use, and \`foundations/\` for the rules behind each token group.
`;

const out = `---\n${yaml(front)}\n---\n\n${body}`;
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (out === current) console.log(`${OUT} up to date`);
else if (CHECK) {
  console.error(`stale: ${OUT}`);
  process.exit(1);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${Object.keys(light).length} colour tokens per mode)`);
}
