import type { Meta, StoryObj } from "@storybook/react"
import { action } from "@storybook/addon-actions"
import {
  Pagination,
  PaginationContent,
  PaginationEllipsis,
  PaginationItem,
  PaginationLink,
  PaginationNext,
  PaginationPrevious,
} from "./pagination"

const meta: Meta<typeof Pagination> = {
  title: "Components/Pagination",
  component: Pagination,
  tags: ["autodocs"],
  parameters: {
    docs: {
      description: {
        component: `
A composable pagination navigation built from sub-components for navigating between pages of content.

**Sub-components:** \`PaginationContent\`, \`PaginationItem\`, \`PaginationLink\`, \`PaginationPrevious\`, \`PaginationNext\`, \`PaginationEllipsis\`

**Import**
\`\`\`tsx
import {
  Pagination,
  PaginationContent,
  PaginationItem,
  PaginationLink,
  PaginationNext,
  PaginationPrevious,
  PaginationEllipsis,
} from "@eluan/core"
\`\`\`

**Usage**
\`\`\`tsx
<Pagination>
  <PaginationContent>
    <PaginationItem>
      <PaginationPrevious href="#" />
    </PaginationItem>
    <PaginationItem>
      <PaginationLink href="#" isActive>1</PaginationLink>
    </PaginationItem>
    <PaginationItem>
      <PaginationNext href="#" />
    </PaginationItem>
  </PaginationContent>
</Pagination>
\`\`\`
        `,
      },
    },
  },
}

