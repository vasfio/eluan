import type {
  Mode,
  PrimitiveTokens,
  Scale,
  ScaleName,
  ScaleStepValue,
  SemanticMap,
  TokenRef,
} from '../types.js';
import { modeRef } from '../tokens/semanticMap.js';

const SCALE_STEPS: ScaleStepValue[] = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

function resolveHex(ref: TokenRef, primitives: PrimitiveTokens): string {
  if (ref === 'white') return '#ffffff';
  if (ref === 'black') return '#000000';
  const [scaleName, stepStr] = ref.split('.') as [ScaleName, string];
  const step = Number(stepStr) as ScaleStepValue;
  const scale = primitives[scaleName];
  if (!scale) {
    throw new Error(`Invalid token reference "${ref}": unknown scale "${scaleName}".`);
  }
  const entry = scale[step];
  if (!entry) {
    throw new Error(`Invalid token reference "${ref}": scale "${scaleName}" has no step ${stepStr}.`);
  }
  return entry.hex;
}

function scaleToW3C(name: string, scale: Scale): Record<string, unknown> {
  const group: Record<string, unknown> = {};
  for (const step of SCALE_STEPS) {
    const entry = scale[step];
    group[String(step)] = {
      $type: 'color',
      $value: entry.hex,
      $extensions: {
        'com.eluan': {
          oklch: { l: entry.oklch.l, c: entry.oklch.c, h: entry.oklch.h },
        },
      },
    };
  }
  return group;
}

export function compilePrimitivesJSON(primitives: PrimitiveTokens): string {
  const doc: Record<string, unknown> = {};
  for (const [name, scale] of Object.entries(primitives)) {
    if (scale) {
      doc[name] = scaleToW3C(name, scale);
    }
  }
  return JSON.stringify(doc, null, 2);
}

export function compileSemanticJSON(
  map: SemanticMap,
  primitives: PrimitiveTokens,
  darkPrimitives: PrimitiveTokens = primitives,
  dimPrimitives: PrimitiveTokens = primitives
): string {
  const doc: Record<string, unknown> = {};
  for (const [token, entry] of Object.entries(map)) {
    const dim = modeRef(entry, 'dim');
    doc[token] = {
      $type: 'color',
      light: {
        $value: resolveHex(entry.light, primitives),
        $ref: entry.light,
      },
      dim: {
        $value: resolveHex(dim, dimPrimitives),
        $ref: dim,
      },
      dark: {
        $value: resolveHex(entry.dark, darkPrimitives),
        $ref: entry.dark,
      },
      role: entry.role,
      ...(entry.contrastAgainst ? { contrastAgainst: entry.contrastAgainst } : {}),
      ...(entry.minContrast ? { minContrast: entry.minContrast } : {}),
      ...(entry.allowBelowDefault ? { allowBelowDefault: true } : {}),
    };
  }
  return JSON.stringify(doc, null, 2);
}

function compilePrimitiveCSSBlock(
  scaleName: string,
  scale: Scale,
  prefix: string
): string {
  const lines: string[] = [];
  for (const step of SCALE_STEPS) {
    const entry = scale[step];
    lines.push(`  --color-${prefix}-${step}: ${entry.hex};`);
  }
  return lines.join('\n');
}

export function compilePrimitivesCSS(
  primitives: PrimitiveTokens,
  themeName: string
): string {
  const blocks: string[] = [];

  for (const [name, scale] of Object.entries(primitives)) {
    if (!scale) continue;
    blocks.push(`\n  /* ${name} */`);
    blocks.push(compilePrimitiveCSSBlock(name, scale, name));
  }

  return `/* Generated by eluan-theme-generator — ${themeName} primitives */\n\n[data-theme="${themeName}"] {\n${blocks.join('\n')}\n}`;
}

type PaletteSteps = Record<'main' | 'background' | 'tint' | 'foreground' | 'shade', ScaleStepValue>;

// Dim is light one step deeper throughout, matching dimRef()
const PALETTE_STEPS: Record<Mode, PaletteSteps> = {
  light: { main: 500, background: 50, tint: 100, foreground: 700, shade: 800 },
  dim: { main: 600, background: 100, tint: 200, foreground: 800, shade: 900 },
  dark: { main: 400, background: 950, tint: 900, foreground: 200, shade: 300 },
};

const NEUTRAL_STEPS: Record<Mode, { bg: Record<string, ScaleStepValue>; fg: Record<string, ScaleStepValue> }> = {
  light: {
    bg: { primary: 50, secondary: 100, tertiary: 200, quaternary: 300, quinary: 400 },
    fg: { primary: 950, secondary: 800, tertiary: 600, quaternary: 500, quinary: 400 },
  },
  dim: {
    bg: { primary: 100, secondary: 200, tertiary: 300, quaternary: 400, quinary: 500 },
    fg: { primary: 950, secondary: 900, tertiary: 700, quaternary: 600, quinary: 500 },
  },
  dark: {
    bg: { primary: 800, secondary: 900, tertiary: 950, quaternary: 700, quinary: 600 },
    fg: { primary: 50, secondary: 100, tertiary: 200, quaternary: 300, quinary: 400 },
  },
};

const MODE_LABELS: Record<Mode, string> = { light: 'Light', dim: 'Dim', dark: 'Dark' };

function compileModeCSSBlock(
  map: SemanticMap,
  primitives: PrimitiveTokens,
  mode: Mode,
  scaleName: ScaleName,
  cssPrefix: string
): string {
  const scale = primitives[scaleName];
  if (!scale) return '';

  const lines: string[] = [];
  for (const [role, step] of Object.entries(PALETTE_STEPS[mode])) {
    lines.push(`  --${cssPrefix}-${role}: ${scale[step].hex};`);
  }

  return lines.join('\n');
}

export function compileModeCSS(
  map: SemanticMap,
  primitives: PrimitiveTokens,
  mode: Mode,
  themeName: string
): string {
  const lines: string[] = [];
  const neutral = primitives.neutral;
  if (!neutral) throw new Error('Neutral scale is required');

  const { bg: bgSteps, fg: fgSteps } = NEUTRAL_STEPS[mode];
  // The semantic map's entries win when present, so this matches css.theme
  // and the custom theme even after a contrast correction moves one.
  const ramp = (token: string, step: ScaleStepValue) =>
    map[token] ? resolveHex(modeRef(map[token], mode), primitives) : neutral[step].hex;

  lines.push(`  /* Backgrounds */`);
  for (const [level, step] of Object.entries(bgSteps)) {
    lines.push(`  --backgrounds-${level}: ${ramp(`backgrounds-${level}`, step)};`);
  }

  lines.push(`\n  /* Foregrounds */`);
  for (const [level, step] of Object.entries(fgSteps)) {
    lines.push(`  --foregrounds-${level}: ${ramp(`foregrounds-${level}`, step)};`);
  }

  const paletteScales: [ScaleName, string][] = [
    ['primary', 'accent'],
    ['error', 'error'],
    ['warning', 'warning'],
    ['success', 'success'],
    ['info', 'info'],
  ];

  for (const [scaleName, cssPrefix] of paletteScales) {
    const block = compileModeCSSBlock(map, primitives, mode, scaleName, cssPrefix);
    if (block) {
      lines.push(`\n  /* ${cssPrefix} */`);
      lines.push(block);
    }
  }

  return `/* Generated by eluan-theme-generator — ${themeName} ${mode} mode */\n\n[data-theme="${themeName}"][data-mode="${mode}"],\n[data-theme="${themeName}"][data-mode="${MODE_LABELS[mode]}"] {\n${lines.join('\n')}\n}`;
}

export function compileThemeCSS(
  map: SemanticMap,
  primitives: PrimitiveTokens,
  themeName: string,
  inputHash: string,
  darkPrimitives: PrimitiveTokens = primitives,
  dimPrimitives: PrimitiveTokens = primitives
): string {
  const lines: string[] = [];

  lines.push(`/* Generated by eluan-theme-generator v0.1.0 */`);
  lines.push(`/* Input hash: ${inputHash} */`);
  lines.push(`/* Theme: ${themeName} */`);

  const sources: Record<Mode, PrimitiveTokens> = { light: primitives, dim: dimPrimitives, dark: darkPrimitives };
  for (const mode of ['light', 'dim', 'dark'] as const) {
    const tokenLines: string[] = [];
    for (const [token, entry] of Object.entries(map)) {
      const ref = modeRef(entry, mode);
      tokenLines.push(`  --${token}: ${resolveHex(ref, sources[mode])}; /* ${ref} */`);
    }
    lines.push('');
    lines.push(`[data-theme="${themeName}"][data-mode="${mode}"],`);
    lines.push(`[data-theme="${themeName}"][data-mode="${MODE_LABELS[mode]}"] {`);
    lines.push(tokenLines.join('\n'));
    lines.push('}');
  }

  return lines.join('\n');
}

export function compileCreateThemeTokens(
  map: SemanticMap,
  primitives: PrimitiveTokens,
  mode: Mode
): Record<string, string> {
  const tokens: Record<string, string> = {};
  for (const [token, entry] of Object.entries(map)) {
    tokens[`--${token}`] = resolveHex(modeRef(entry, mode), primitives);
  }
  return tokens;
}

/**
 * CSS for a custom theme layered on `minimal`, in the same shape `createTheme()`
 * from @eluan/core emits: the light tokens on `[data-theme-custom="<name>"]`
 * and the dim and dark tokens on that plus `[data-mode]`. Because the theme
 * sits on top of `minimal` instead of replacing it, `minimal`'s fonts stay in
 * place. Without `dim`, dim mode uses the light tokens.
 */
export function compileCustomThemeCSS(
  themeName: string,
  light: Record<string, string>,
  dark: Record<string, string>,
  dim?: Record<string, string>
): string {
  const name = themeName.replace(/["\\]/g, '\\$&');
  const body = (tokens: Record<string, string>) =>
    Object.entries(tokens)
      .map(([prop, value]) => `  ${prop}: ${value};`)
      .join('\n');
  const modeBlock = (mode: Mode, tokens: Record<string, string>) =>
    `[data-theme-custom="${name}"][data-mode="${mode}"],\n[data-theme-custom="${name}"][data-mode="${MODE_LABELS[mode]}"] {\n${body(tokens)}\n}`;
  return [
    `[data-theme-custom="${name}"] {\n${body(light)}\n}`,
    ...(dim ? [modeBlock('dim', dim)] : []),
    modeBlock('dark', dark),
  ].join('\n\n');
}
